  function isSupportedLang(lang) {
    return typeof lang === 'string' && supportedLangs.indexOf(lang.toLowerCase()) !== -1;
  }

  function translate(lang, key, vars) {
    const safeLang = isSupportedLang(lang) ? lang.toLowerCase() : 'tr';
    const dict = translations[safeLang] || translations.tr;
    let text = dict[key];
    if (text === undefined) text = translations.en[key];
    if (text === undefined) text = translations.tr[key];
    if (text === undefined) return key;

    if (vars && typeof vars === 'object') {
      Object.keys(vars).forEach((k) => {
        text = text.split(`{${k}}`).join(String(vars[k]));
      });
    }
    return text;
  }

  function formatPercent(value, lang) {
    const num = value !== undefined && value !== null ? value : 100;
    return String(lang || 'tr').toLowerCase() === 'tr' ? `%${num}` : `${num}%`;
  }

  function getLocale(lang) {
    const safeLang = isSupportedLang(lang) ? lang.toLowerCase() : 'tr';
    return localeMap[safeLang] || 'tr-TR';
  }

